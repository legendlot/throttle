// Regenerates src/openai-cidrs.js from OpenAI's published ChatGPT-connector egress ranges.
// OpenAI says the ranges change and should be re-fetched regularly (developers.openai.com/api/docs/guides/ip-addresses).
// Run: node scripts/refresh-openai-cidrs.mjs   then npm test, commit, push, deploy.
import { writeFileSync } from 'node:fs';
const URL_ = 'https://openai.com/chatgpt-connectors.json';
const res = await fetch(URL_, { headers: { 'User-Agent': 'lotmcp-refresh' } });
if (!res.ok) throw new Error(`${URL_} ${res.status}`);
const j = await res.json();
const v4 = (j.prefixes || []).map(p => p.ipv4Prefix).filter(Boolean);
if (v4.length < 50) throw new Error(`only ${v4.length} IPv4 prefixes; refusing to shrink the allowlist`);
for (const c of v4) if (!/^\d{1,3}(\.\d{1,3}){3}\/([0-9]|[12][0-9]|3[0-2])$/.test(c)) throw new Error(`bad prefix ${c}`);
const broad = v4.filter(c => Number(c.split('/')[1]) < 23);
if (broad.length) console.log(`note: ${broad.length} prefix(es) broader than /23 are written but DROPPED at runtime (src/clients.js MIN_PREFIX_LEN): ${broad.join(', ')}`);
writeFileSync(new URL('../src/openai-cidrs.js', import.meta.url),
  `// GENERATED by scripts/refresh-openai-cidrs.mjs from ${URL_}. Do not edit by hand.\n` +
  `export const OPENAI_CIDRS_AS_OF = ${JSON.stringify(j.creationTime || null)};\n` +
  `export const OPENAI_CONNECTOR_CIDRS = ${JSON.stringify(v4, null, 0).replace(/","/g, '", "')};\n`);
console.log(`wrote ${v4.length} prefixes (as of ${j.creationTime})`);
